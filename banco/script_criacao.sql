-- =============================================================================
-- HermesPDV — script_criacao.sql
-- Criação do banco de dados, tabelas, chaves, índices e restrições.
-- SGBD: PostgreSQL 14 ou superior
--
-- Como executar (terminal):
--   psql -U postgres -f script_criacao.sql
--
-- Como executar no pgAdmin:
--   1. Conectado ao banco "postgres", execute apenas a PARTE 1.
--   2. Abra o Query Tool no banco "hermespdv" e execute a PARTE 2
--      (do comentário "PARTE 2" até o fim; a linha \connect é só para o psql).
--
-- Convenções: nomes em minúsculo, sem acento, com underscore e no singular.
-- Chave primária: id_<tabela>. Chave estrangeira: mesmo nome da chave referenciada.
-- =============================================================================

SET client_encoding = 'UTF8';

-- -----------------------------------------------------------------------------
-- PARTE 1 — banco de dados
-- -----------------------------------------------------------------------------
DROP DATABASE IF EXISTS hermespdv;
CREATE DATABASE hermespdv WITH ENCODING 'UTF8' TEMPLATE template0;

\connect hermespdv

-- -----------------------------------------------------------------------------
-- PARTE 2 — tabelas
-- -----------------------------------------------------------------------------
SET client_encoding = 'UTF8';

-- Usuários do sistema e seus perfis de acesso (RF03, RF04, RN04, RNF02)
CREATE TABLE usuario (
    id_usuario   INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(100) NOT NULL,
    login        VARCHAR(30)  NOT NULL,
    senha_hash   VARCHAR(60)  NOT NULL,
    perfil       VARCHAR(13)  NOT NULL,
    ativo        BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_login UNIQUE (login),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMINISTRADOR', 'GERENTE', 'ATENDENTE'))
);

-- Clientes identificados nas vendas (RF02, RN06)
CREATE TABLE cliente (
    id_cliente   INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(120) NOT NULL,
    cpf_cnpj     VARCHAR(14)  NOT NULL,
    email        VARCHAR(120),
    telefone     VARCHAR(15),
    criado_em    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_cpf_cnpj UNIQUE (cpf_cnpj),
    -- somente dígitos: 11 (CPF) ou 14 (CNPJ)
    CONSTRAINT ck_cliente_cpf_cnpj CHECK (cpf_cnpj ~ '^([0-9]{11}|[0-9]{14})$')
);

-- Categorias de produtos (RF01)
CREATE TABLE categoria (
    id_categoria INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(60)  NOT NULL,
    descricao    VARCHAR(200),
    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_nome UNIQUE (nome)
);

-- Produtos e saldo em estoque (RF01, RF09, RF17, RN05, RN07)
CREATE TABLE produto (
    id_produto         INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    codigo             VARCHAR(20)   NOT NULL,
    nome               VARCHAR(120)  NOT NULL,
    id_categoria       INTEGER       NOT NULL,
    preco_custo        NUMERIC(10,2) NOT NULL DEFAULT 0,
    preco_venda        NUMERIC(10,2) NOT NULL,
    quantidade_estoque INTEGER       NOT NULL DEFAULT 0,
    estoque_minimo     INTEGER       NOT NULL DEFAULT 0,
    ativo              BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_produto PRIMARY KEY (id_produto),
    CONSTRAINT uq_produto_codigo UNIQUE (codigo),
    CONSTRAINT fk_produto_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_produto_preco_custo CHECK (preco_custo >= 0),
    CONSTRAINT ck_produto_preco_venda CHECK (preco_venda > 0),
    CONSTRAINT ck_produto_quantidade CHECK (quantidade_estoque >= 0),   -- RN02
    CONSTRAINT ck_produto_estoque_minimo CHECK (estoque_minimo >= 0)
);

-- Formas de pagamento aceitas (RF07)
CREATE TABLE forma_pagamento (
    id_forma_pagamento SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    nome               VARCHAR(30) NOT NULL,
    permite_troco      BOOLEAN     NOT NULL DEFAULT FALSE,
    ativo              BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_forma_pagamento PRIMARY KEY (id_forma_pagamento),
    CONSTRAINT uq_forma_pagamento_nome UNIQUE (nome)
);

-- Vendas (RF05, RF06, RF11, RF12, RN01, RN03, RNF05)
CREATE TABLE venda (
    id_venda                INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    data_hora               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario              INTEGER       NOT NULL,
    id_cliente              INTEGER,
    subtotal                NUMERIC(10,2) NOT NULL,
    desconto                NUMERIC(10,2) NOT NULL DEFAULT 0,
    valor_total             NUMERIC(10,2) NOT NULL,
    status                  VARCHAR(9)    NOT NULL DEFAULT 'CONCLUIDA',
    cancelada_em            TIMESTAMP,
    id_usuario_cancelamento INTEGER,
    motivo_cancelamento     VARCHAR(200),
    CONSTRAINT pk_venda PRIMARY KEY (id_venda),
    CONSTRAINT fk_venda_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_venda_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_venda_usuario_cancelamento FOREIGN KEY (id_usuario_cancelamento)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_venda_status CHECK (status IN ('CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_venda_valores CHECK (subtotal >= 0 AND desconto >= 0 AND desconto <= subtotal),
    CONSTRAINT ck_venda_total CHECK (valor_total = subtotal - desconto),
    -- dados de cancelamento existem se, e somente se, a venda estiver cancelada
    CONSTRAINT ck_venda_cancelamento CHECK (
        (status = 'CONCLUIDA' AND cancelada_em IS NULL AND id_usuario_cancelamento IS NULL
                              AND motivo_cancelamento IS NULL)
     OR (status = 'CANCELADA' AND cancelada_em IS NOT NULL AND id_usuario_cancelamento IS NOT NULL
                              AND motivo_cancelamento IS NOT NULL)
    )
);

-- Itens de cada venda: entidade associativa entre venda e produto (N:N)
CREATE TABLE item_venda (
    id_item_venda  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_venda       INTEGER       NOT NULL,
    id_produto     INTEGER       NOT NULL,
    quantidade     INTEGER       NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_item_venda PRIMARY KEY (id_item_venda),
    CONSTRAINT uq_item_venda_produto UNIQUE (id_venda, id_produto),
    CONSTRAINT fk_item_venda_venda FOREIGN KEY (id_venda)
        REFERENCES venda (id_venda) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_item_venda_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON UPDATE CASCADE ON DELETE RESTRICT,   -- RN05
    CONSTRAINT ck_item_venda_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_venda_preco CHECK (preco_unitario >= 0)
);

-- Pagamentos de cada venda: entidade associativa entre venda e forma_pagamento (N:N)
CREATE TABLE pagamento (
    id_pagamento       INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_venda           INTEGER       NOT NULL,
    id_forma_pagamento SMALLINT      NOT NULL,
    valor              NUMERIC(10,2) NOT NULL,
    valor_recebido     NUMERIC(10,2),
    CONSTRAINT pk_pagamento PRIMARY KEY (id_pagamento),
    CONSTRAINT fk_pagamento_venda FOREIGN KEY (id_venda)
        REFERENCES venda (id_venda) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_pagamento_forma FOREIGN KEY (id_forma_pagamento)
        REFERENCES forma_pagamento (id_forma_pagamento) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_recebido CHECK (valor_recebido IS NULL OR valor_recebido >= valor)
);

-- Alertas de estoque baixo (RF10, RN07)
CREATE TABLE alerta_estoque (
    id_alerta_estoque     INTEGER   GENERATED BY DEFAULT AS IDENTITY,
    id_produto            INTEGER   NOT NULL,
    data_hora             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    quantidade_no_momento INTEGER   NOT NULL,
    resolvido             BOOLEAN   NOT NULL DEFAULT FALSE,
    resolvido_em          TIMESTAMP,
    CONSTRAINT pk_alerta_estoque PRIMARY KEY (id_alerta_estoque),
    CONSTRAINT fk_alerta_estoque_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_alerta_estoque_quantidade CHECK (quantidade_no_momento >= 0),
    CONSTRAINT ck_alerta_estoque_resolvido CHECK (resolvido = (resolvido_em IS NOT NULL))
);

-- -----------------------------------------------------------------------------
-- Índices
-- (chaves primárias e UNIQUE já criam índice automaticamente)
-- -----------------------------------------------------------------------------
-- busca de produto por nome na tela de venda e no cadastro (RF17, RNF03)
CREATE INDEX idx_produto_nome ON produto (LOWER(nome));
CREATE INDEX idx_produto_categoria ON produto (id_categoria);
-- consultas e relatórios por período (RF11, RF14)
CREATE INDEX idx_venda_data_hora ON venda (data_hora);
CREATE INDEX idx_venda_usuario ON venda (id_usuario);
CREATE INDEX idx_venda_cliente ON venda (id_cliente);
CREATE INDEX idx_item_venda_produto ON item_venda (id_produto);
CREATE INDEX idx_pagamento_venda ON pagamento (id_venda);
CREATE INDEX idx_pagamento_forma ON pagamento (id_forma_pagamento);
-- no máximo um alerta em aberto por produto (RN07)
CREATE UNIQUE INDEX uq_alerta_estoque_aberto ON alerta_estoque (id_produto) WHERE resolvido = FALSE;

-- -----------------------------------------------------------------------------
-- Comentários (documentação dentro do banco)
-- -----------------------------------------------------------------------------
COMMENT ON TABLE usuario IS 'Usuários do sistema e perfil de acesso';
COMMENT ON TABLE cliente IS 'Clientes identificados nas vendas (opcional na venda)';
COMMENT ON TABLE categoria IS 'Categorias de produtos';
COMMENT ON TABLE produto IS 'Produtos vendidos e saldo em estoque';
COMMENT ON TABLE forma_pagamento IS 'Formas de pagamento aceitas';
COMMENT ON TABLE venda IS 'Vendas realizadas; canceladas permanecem no histórico';
COMMENT ON TABLE item_venda IS 'Itens de cada venda, com o preço praticado no momento';
COMMENT ON TABLE pagamento IS 'Pagamentos de cada venda; vários por venda no pagamento dividido';
COMMENT ON TABLE alerta_estoque IS 'Alertas gerados quando o estoque chega ao mínimo';
COMMENT ON COLUMN venda.subtotal IS 'Soma de quantidade x preco_unitario dos itens (armazenado para histórico)';
COMMENT ON COLUMN venda.valor_total IS 'subtotal - desconto (armazenado para relatórios)';
COMMENT ON COLUMN pagamento.valor_recebido IS 'Somente em dinheiro: valor entregue pelo cliente; troco = valor_recebido - valor';
